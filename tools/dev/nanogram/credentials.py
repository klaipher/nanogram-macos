"""Generates the gitignored NanogramSecrets.swift from ~/.config/telegram-ios/api-credentials.json.

The api_hash is a secret: it is written only into the generated file (mode 0600) and never printed.
"""
from __future__ import annotations

import json
import os
import re
import sys
import tempfile
from pathlib import Path

from nanogram import config

SECRETS_SWIFT = config.ROOT / "packages" / "ApiCredentials" / "Sources" / "ApiCredentials" / "NanogramSecrets.swift"
MISSING_HINT = 'api-credentials.json missing: put {"api_id":…,"api_hash":…} in ~/.config/telegram-ios/'
INT32_MAX = 2**31 - 1


def _read(src: Path) -> tuple[int, str]:
    if not src.is_file():
        raise config.ConfigError(MISSING_HINT)
    try:
        data = json.loads(src.read_text())
        api_id = int(str(data["api_id"]).strip())
        api_hash = str(data["api_hash"]).strip()
    except (ValueError, KeyError, TypeError):
        raise config.ConfigError(f"{src}: needs an integer api_id and a string api_hash") from None
    if not 0 < api_id <= INT32_MAX:
        raise config.ConfigError(f"{src}: api_id must be a positive 32-bit integer")
    if not re.fullmatch(r"[0-9a-f]{32}", api_hash):
        raise config.ConfigError(f"{src}: api_hash must be 32 lowercase hex characters (value not shown)")
    return api_id, api_hash


def render(api_id: int, api_hash: str) -> str:
    return (
        "// Generated by tools/dev/nanogram/credentials.py from ~/.config/telegram-ios/api-credentials.json.\n"
        "// Gitignored; never commit.\n"
        "enum NanogramSecrets {\n"
        f"    static let apiId: Int32 = {api_id}\n"
        f'    static let apiHash: String = "{api_hash}"\n'
        "}\n"
    )


def write_secrets(src: Path, dst: Path) -> bool:
    """Writes dst (mode 0600) only if its content changes; returns True when it wrote."""
    content = render(*_read(Path(src)))
    dst = Path(dst)
    if dst.is_file() and dst.read_text() == content:
        if (dst.stat().st_mode & 0o777) != 0o600:
            os.chmod(dst, 0o600)
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=dst.parent, prefix=".NanogramSecrets.")
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w") as handle:
            handle.write(content)
        os.replace(tmp, dst)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    return True


def main() -> int:
    try:
        wrote = write_secrets(config.api_credentials_path(), SECRETS_SWIFT)
    except config.ConfigError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    rel = SECRETS_SWIFT.relative_to(config.ROOT)
    print(f"credentials: {'wrote' if wrote else 'unchanged'} {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
